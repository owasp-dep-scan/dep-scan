#!/usr/bin/env python3
"""Validate the pre-generated repo-test data of one project.

Four commands run in different places:

* ``staleness`` refuses stale or empty data. Every BOM must name cdxgen
  MIN_CDXGEN_VERSION or later in ``metadata.tools``, and every reachables
  slice must be in the atom 4 shape dep-scan reads: a bare JSON array of
  ``{"flows": [...], "purls": [...]}`` objects (atom 2 wrapped the same
  objects in a top-level ``{"reachables": [...]}``, which dep-scan silently
  skips). The project's slices must hold at least one flow carrying a
  ``pkg:`` purl; a project with ``minReachablePurls`` 0 records that its
  slices carry no package identity (C and C++ code), and needs at least one
  flow at all. Uses only the standard library so the composite action can
  run it on any runner before the project is installed.
* ``assert`` runs the reachability analyzers the repo tests use over the
  data directory and fails when fewer distinct purls are reached than the
  project's ``minReachablePurls`` in projects.json, or when a ``mustReach``
  package name is missing from the reached purls. Requires the dep-scan
  packages to be importable (``uv run python contrib/repotests/validate.py``).
* ``digests`` verifies every file of a pulled OCI artifact against the layer
  digests of its manifest, and refuses files the manifest does not list.
* ``lock`` writes testdata.lock.json from the generation.json files of a
  data root plus the OCI descriptors the publish job fetched after pushing.

Usage:
  validate.py staleness DATA_DIR --projects projects.json --name rustpad
  validate.py assert DATA_DIR --projects projects.json --name rustpad
  validate.py digests DATA_DIR --manifest manifest.json [--digest sha256:...]
  validate.py lock --data-root OUT_ROOT --lock-out testdata.lock.json \
      --registry ghcr.io/owasp-dep-scan/depscan-testdata
"""

import argparse
import hashlib
import json
import re
import sys
import urllib.parse
from pathlib import Path

# The repo tests assert results of data generated by cdxgen 13.8 with atom 4.
MIN_CDXGEN_VERSION = (13, 8, 0)

BOM_GLOB = "sbom-*.cdx.json"
REACHABLES_GLOB = "*reachables*.slices*.json"


class ValidationFailure(Exception):
    """One or more checks failed; the message lists them all."""


def load_projects(projects_path, name):
    with open(projects_path, encoding="utf-8") as fp:
        projects = json.load(fp)["projects"]
    entry = next((p for p in projects if p["name"] == name), None)
    if entry is None:
        raise ValidationFailure(f"No project named {name} in {projects_path}")
    return entry


def iter_json_array(text, name):
    """Yield the elements of the top-level JSON array in ``text``.

    The slice reader in analysis_lib.reachability parses only this shape, so
    a file that is not a bare JSON array is reported here rather than
    skipped. A truncated or malformed array raises too: the reader would
    keep the flows before the damage and drop the rest without a word.
    Reimplemented with the standard library so ``staleness`` stays
    dependency-free for the composite action.
    """
    decoder = json.JSONDecoder()
    whitespace = " \t\n\r"
    n = len(text)
    idx = 0
    while idx < n and text[idx] in whitespace:
        idx += 1
    if idx >= n or text[idx] != "[":
        raise ValidationFailure(
            f"{name}: not a bare JSON array (starts {text[idx : idx + 16]!r});"
            " regenerate with atom 4"
        )
    idx += 1
    while True:
        while idx < n and text[idx] in whitespace:
            idx += 1
        if idx < n and text[idx] == "]":
            return
        try:
            obj, idx = decoder.raw_decode(text, idx)
        except json.JSONDecodeError as exc:
            raise ValidationFailure(f"{name}: malformed JSON array ({exc})") from exc
        yield obj
        while idx < n and text[idx] in whitespace:
            idx += 1
        if idx < n and text[idx] == ",":
            idx += 1
        elif idx >= n or text[idx] != "]":
            raise ValidationFailure(f"{name}: truncated JSON array at offset {idx}")


def parse_version(text):
    numbers = re.findall(r"\d+", str(text or ""))
    return tuple(int(piece) for piece in numbers[:3])


def cdxgen_tool_versions(bom):
    """Every cdxgen version a BOM names in metadata.tools.

    CycloneDX 1.6 writes ``tools`` as a list; 1.7 and later write a dict
    with ``components`` and ``services``. Both shapes are collected.
    """
    tools = (bom.get("metadata") or {}).get("tools")
    if tools is None:
        return []
    entries = tools if isinstance(tools, list) else []
    if isinstance(tools, dict):
        entries = list(tools.get("components") or []) + list(tools.get("services") or [])
    return [
        entry.get("version")
        for entry in entries
        if isinstance(entry, dict) and entry.get("name") == "cdxgen"
    ]


#: The dosai report names a published project directory may hold, in the
#: order dep-scan's BOM directory scan looks for them (``_dosai_report_names``
#: in depscan/lib/bom.py, for a dotnet scan; a test pins the two lists
#: together). The two raw artifacts of a direct dosai run come first, then
#: any other report under analysis/dosai/, then the report cdxgen persists and
#: the cdxgen evinse name.
DOSAI_RAW_REPORTS = (
    "analysis/dosai/dotnet-dataflows.json",
    "analysis/dosai/dotnet-methods.json",
    "dotnet-semantics.slices.json",
    "csharp-data-flow.slices.json",
)

#: The two raw artifacts of a direct dosai run, read together when present.
_DOSAI_RAW_HALVES = DOSAI_RAW_REPORTS[:2]


def _read_dosai_report(path):
    try:
        report = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return None
    if not isinstance(report, dict):
        return None
    metadata = report.get("Metadata")
    if isinstance(metadata, dict) and metadata.get("Tool") == "Dosai":
        return report
    return None


def _dosai_raw_reports(data_path):
    """The parsed dosai reports a published project directory carries, in
    the order dep-scan reads them: both raw halves of a direct run when
    either is there, else the first readable report of the other names.
    Empty when the directory holds none."""
    halves = [data_path / name for name in _DOSAI_RAW_HALVES]
    if any(path.is_file() for path in halves):
        return [report for path in halves if (report := _read_dosai_report(path)) is not None]
    candidates = []
    analysis_dir = data_path / "analysis" / "dosai"
    if analysis_dir.is_dir():
        raw_names = {Path(name).name for name in _DOSAI_RAW_HALVES}
        candidates.extend(
            path
            for path in sorted(analysis_dir.iterdir())
            if path.suffix == ".json" and path.name not in raw_names
        )
    candidates.extend(data_path / name for name in DOSAI_RAW_REPORTS if "/" not in name)
    for path in candidates:
        if path.is_file() and (report := _read_dosai_report(path)) is not None:
            return [report]
    return []


def _dosai_package_entries(report):
    """Every PackageReachability entry of a dosai report: a combined report
    keeps them in its dataflows and methods halves, a single artifact at its
    top level."""
    entries = []
    for part in (report, report.get("dataflows"), report.get("methods")):
        if isinstance(part, dict):
            entries.extend(
                entry for entry in part.get("PackageReachability") or [] if isinstance(entry, dict)
            )
    return entries


def check_staleness(data_dir, entry):
    """Decisions on staleness: current cdxgen, atom 4 shape, non-empty flows.

    A project whose ``minReachablePurls`` is 0 records that its slices carry
    no package identity (C and C++ code has no purls to attach, in atom 2 as
    in atom 4); for those, at least one flow must exist. Every other project
    must have at least one flow carrying a ``pkg:`` purl. A dosai report's
    PackageReachability entries count as flows, so a .NET project whose
    data holds only dosai's raw reports gets the same checks.
    """
    failures = []
    data_path = Path(data_dir)
    bom_files = sorted(data_path.glob(BOM_GLOB))
    if not bom_files:
        failures.append(f"no BOM files matching {BOM_GLOB} in {data_dir}")
    for bom_file in bom_files:
        try:
            bom = json.loads(bom_file.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            failures.append(f"{bom_file.name}: unreadable BOM ({exc})")
            continue
        versions = cdxgen_tool_versions(bom)
        if not versions:
            failures.append(f"{bom_file.name}: metadata.tools names no cdxgen")
            continue
        if max(parse_version(v) for v in versions) < MIN_CDXGEN_VERSION:
            failures.append(
                f"{bom_file.name}: generated by cdxgen {', '.join(map(str, versions))},"
                f" {MIN_CDXGEN_VERSION[0]}.{MIN_CDXGEN_VERSION[1]}.{MIN_CDXGEN_VERSION[2]}"
                " or later is required"
            )

    slice_files = sorted(data_path.glob(REACHABLES_GLOB))
    flows = 0
    flows_with_purl = 0
    dosai_reports = _dosai_raw_reports(data_path)
    if not slice_files and not dosai_reports:
        failures.append(f"no reachables slice files matching {REACHABLES_GLOB} in {data_dir}")
    # A .NET project's published data carries dosai's raw reports instead of
    # a converted reachables slice; the packages' purls live in the reports'
    # PackageReachability entries, and count like flows with a purl.
    for report in dosai_reports:
        for package in _dosai_package_entries(report):
            flows += 1
            purl = package.get("Purl")
            if isinstance(purl, str) and purl.startswith("pkg:"):
                flows_with_purl += 1
    for slice_file in slice_files:
        try:
            text = slice_file.read_text(encoding="utf-8")
            for flow in iter_json_array(text, slice_file.name):
                flows += 1
                if not (
                    isinstance(flow, dict)
                    and isinstance(flow.get("flows"), list)
                    and isinstance(flow.get("purls"), list)
                ):
                    raise ValidationFailure(
                        f"{slice_file.name}: flow object without flows/purls lists,"
                        " not the atom 4 shape"
                    )
                if any(isinstance(p, str) and p.startswith("pkg:") for p in flow["purls"]):
                    flows_with_purl += 1
        except (OSError, UnicodeDecodeError) as exc:
            failures.append(f"{slice_file.name}: unreadable slice ({exc})")
        except ValidationFailure as exc:
            failures.append(str(exc))
    if not failures and (slice_files or dosai_reports):
        inputs = f"{len(slice_files)} slice files and {len(dosai_reports)} dosai reports"
        if entry.get("minReachablePurls", 0) > 0 and flows_with_purl == 0:
            failures.append(f"no flow with a pkg: purl across {inputs}")
        elif flows == 0:
            failures.append(f"no flow at all across {inputs}")
    if failures:
        raise ValidationFailure("\n".join(failures))
    return {
        "bomFiles": len(bom_files),
        "sliceFiles": len(slice_files),
        "flows": flows,
        "flowsWithPurl": flows_with_purl,
    }


def versionless_purl(purl):
    """Strip the version: pkg:npm/%40scope/name@1.2.3 -> pkg:npm/%40scope/name."""
    base = purl.split("?", 1)[0]
    tail = base.rsplit("/", 1)[-1]
    if "@" in tail:
        base = base.rsplit("@", 1)[0]
    return base


def purl_package_names(purl):
    """The names a mustReach entry may match: the last path segment, and the
    last two for scoped packages such as @types/node."""
    base = versionless_purl(purl)
    path = base[len("pkg:") :].split("/", 1)[-1].rstrip("/")
    segments = [urllib.parse.unquote(piece) for piece in path.split("/")]
    names = {segments[-1]}
    if len(segments) >= 2:
        names.add(f"{segments[-2]}/{segments[-1]}")
    return names


def run_reachability(data_dir, analyzer):
    """Run the analyzers exactly as the repo tests' depscan invocation does
    for a scan of a BOM directory: the adapters read the reports the
    directory holds, their records go into an evidence store, and the
    engine counts the reached purls from that store. The store is written
    to a scratch directory so the pinned data is never modified."""
    import os
    import tempfile

    from analysis_lib import ReachabilityAnalysisKV
    from analysis_lib.evidence import store as evidence_store
    from analysis_lib.evidence.adapters import atom as atom_adapter
    from analysis_lib.reachability import get_reachability_impl
    from depscan.lib import bom as bom_mod

    with tempfile.TemporaryDirectory() as scratch:
        options = ReachabilityAnalysisKV(
            project_types=["bom"],
            src_dir=str(data_dir),
            bom_dir=str(data_dir),
            evidence_file=os.path.join(scratch, evidence_store.EVIDENCE_FILE),
        )
        results = bom_mod.discover_reachability_reports(
            str(data_dir),
            ["bom"],
            {"reachability_analyzer": analyzer},
            options.bom_files,
        )
        # atom's slices are its own native output, so its adapter reads them
        # here, exactly as the enrichment stage of a scan does.
        stems = tuple(
            file_name.split(".slices", 1)[0]
            for file_name in bom_mod.reachability_slice_files().values()
        )
        reachables, usages, callsites = [], [], []
        for path in options.slices_files or []:
            name = os.path.basename(path)
            if "reachables.slices" in name and not name.startswith(stems):
                reachables.append(path)
            elif "usages.slices" in name:
                usages.append(path)
            elif "callsites.slices" in name:
                callsites.append(path)
        atom_result = atom_adapter.extract(
            reachables,
            producer_version="",
            usages_files=usages,
            callsites_files=callsites,
            openapi_files=options.openapi_spec_files,
        )
        if atom_result.status == "completed":
            results["atom"] = atom_result
        records = [
            record
            for result in results.values()
            if result.status == "completed"
            for record in result.records
        ]
        evidence_store.write(options.evidence_file, records)
        result = get_reachability_impl(analyzer, options).process()
    if not result or not result.success:
        raise ValidationFailure(f"{analyzer} reported failure over {data_dir}")
    return result


def check_assert(data_dir, entry, analyzer):
    summary = check_staleness(data_dir, entry)
    result = run_reachability(data_dir, analyzer)
    reached = result.reached_purls or {}
    failures = []
    min_reachable = entry.get("minReachablePurls", 0)
    if len(reached) < min_reachable:
        failures.append(
            f"{len(reached)} distinct reached purls, projects.json requires"
            f" at least {min_reachable}"
        )
    reached_names = set()
    for purl in reached:
        reached_names |= purl_package_names(purl)
    for must in entry.get("mustReach") or []:
        if not any(must == name or name.endswith(f"/{must}") for name in reached_names):
            failures.append(f"mustReach package {must} was not reached")
    summary["reachedPurls"] = len(reached)
    summary["analyzer"] = analyzer
    if failures:
        failures.append(f"reached purls: {sorted(reached)}")
        raise ValidationFailure("\n".join(failures))
    return summary


def check_digests(data_dir, manifest_path, manifest_digest=None):
    """Verify the pulled files against the OCI manifest layer digests.

    With ``manifest_digest`` (the digest testdata.lock.json pins), the
    manifest file itself must hash to it first, so a manifest restored from
    a cache cannot vouch for files the pinned generation does not hold.
    """
    try:
        manifest_bytes = Path(manifest_path).read_bytes()
    except OSError as exc:
        raise ValidationFailure(f"{manifest_path}: unreadable manifest ({exc})") from exc
    if manifest_digest is not None:
        actual = "sha256:" + hashlib.sha256(manifest_bytes).hexdigest()
        if actual != manifest_digest:
            raise ValidationFailure(
                f"{manifest_path}: manifest digest {actual} is not the pinned {manifest_digest}"
            )
    manifest = json.loads(manifest_bytes)
    layers = {}
    for layer in manifest.get("layers") or []:
        title = (layer.get("annotations") or {}).get("org.opencontainers.image.title")
        if title:
            layers[title] = layer
    if not layers:
        raise ValidationFailure(f"{manifest_path} carries no titled file layers")
    failures = []
    data_path = Path(data_dir)
    if not data_path.is_dir():
        raise ValidationFailure(f"{data_dir} does not exist or is not a directory")
    local_files = {p.name for p in data_path.iterdir() if p.is_file()}
    for title, layer in sorted(layers.items()):
        local = data_path / title
        if not local.is_file():
            failures.append(f"{title}: listed in the manifest but not pulled")
            continue
        digest = layer.get("digest", "")
        actual = "sha256:" + hashlib.sha256(local.read_bytes()).hexdigest()
        if actual != digest:
            failures.append(f"{title}: digest {actual} does not match {digest}")
        if local.stat().st_size != layer.get("size"):
            failures.append(
                f"{title}: size {local.stat().st_size} does not match {layer.get('size')}"
            )
    for extra in sorted(local_files - set(layers)):
        failures.append(f"{extra}: present in the data directory but not in the manifest")
    if failures:
        raise ValidationFailure("\n".join(failures))
    return {"verifiedFiles": len(layers)}


def write_lock(data_root, lock_out, registry):
    """Build testdata.lock.json from per-project generation.json files and the
    OCI descriptors the publish job fetched after pushing each artifact."""
    projects = {}
    for project_dir in sorted(Path(data_root).iterdir()):
        generation_file = project_dir / "generation.json"
        descriptor_file = project_dir / "descriptor.json"
        if not generation_file.is_file():
            continue
        if not descriptor_file.is_file():
            raise ValidationFailure(
                f"{project_dir.name}: generation.json without descriptor.json;"
                " publish must fetch the descriptor after pushing"
            )
        with open(generation_file, encoding="utf-8") as fp:
            generation = json.load(fp)
        with open(descriptor_file, encoding="utf-8") as fp:
            descriptor = json.load(fp)
        digest = descriptor.get("digest")
        if not str(digest or "").startswith("sha256:"):
            raise ValidationFailure(f"{project_dir.name}: descriptor carries no sha256 digest")
        projects[generation["name"]] = {
            "manifestDigest": digest,
            "tag": generation["tag"],
            "generators": {
                "cdxgen": generation["cdxgenVersion"],
                "atom": generation["atomVersion"],
                "cdxgenPlugins": generation["cdxgenPluginsVersion"],
            },
            "source": {"git": generation["git"], "commit": generation["commit"]},
            "generated": generation["generated"],
        }
    if not projects:
        raise ValidationFailure(f"No project with generation.json under {data_root}")
    lock = {"schema": 1, "registry": registry, "projects": projects}
    with open(lock_out, "w", encoding="utf-8") as fp:
        json.dump(lock, fp, indent=2, sort_keys=True)
        fp.write("\n")
    return {"projects": sorted(projects)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p_stale = sub.add_parser("staleness", help="refuse stale or empty data")
    p_stale.add_argument("data_dir")
    p_stale.add_argument("--projects", required=True)
    p_stale.add_argument("--name", required=True)

    p_assert = sub.add_parser("assert", help="assert reachable purl counts")
    p_assert.add_argument("data_dir")
    p_assert.add_argument("--projects", required=True)
    p_assert.add_argument("--name", required=True)
    p_assert.add_argument("--analyzer", default="SemanticReachability")

    p_dig = sub.add_parser("digests", help="verify pulled files against a manifest")
    p_dig.add_argument("data_dir")
    p_dig.add_argument("--manifest", required=True)
    p_dig.add_argument(
        "--digest", help="manifest digest the lock file pins; the manifest must hash to it"
    )

    p_lock = sub.add_parser("lock", help="write testdata.lock.json")
    p_lock.add_argument("--data-root", required=True)
    p_lock.add_argument("--lock-out", required=True)
    p_lock.add_argument("--registry", required=True)

    args = parser.parse_args(argv)
    try:
        if args.command == "staleness":
            entry = load_projects(args.projects, args.name)
            summary = check_staleness(args.data_dir, entry)
        elif args.command == "assert":
            entry = load_projects(args.projects, args.name)
            summary = check_assert(args.data_dir, entry, args.analyzer)
        elif args.command == "digests":
            summary = check_digests(args.data_dir, args.manifest, args.digest)
        else:
            summary = write_lock(args.data_root, args.lock_out, args.registry)
    except ValidationFailure as exc:
        print(f"FAILED {args.command}: {exc}", file=sys.stderr)
        return 1
    print(f"OK {args.command}: {json.dumps(summary, sort_keys=True)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
