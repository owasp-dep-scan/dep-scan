#!/usr/bin/env python3
"""check_agent_plugin.py: structural checks for the coding-agent plugin in
agent-plugin/ that ``claude plugin validate`` does not make.

The release version lives in pyproject.toml and flows into every manifest
through contrib/gen_agent_manifests.py; the two have drifted before, so the
manifest versions are compared against the pyproject version through the
same PEP 440 to semver conversion the generator applies. Agent Skills
clients other than Claude Code (Codex, Copilot, Cursor) reject a skill whose
name does not match its directory or whose description is over the spec's
1024-character limit, and they parse the frontmatter with strict YAML
parsers, so an unquoted ": " in a description loses the skill there. The
plugin ships two identical MCP server configurations (.mcp.json for Claude
Code, mcp.json for Codex); the check keeps them identical.

The manifests are generated by contrib/gen_agent_manifests.py; this check
fails when a committed manifest differs from the generated output and when
agent-plugin/plugin.json does not validate against the vendored Agent
Plugins schema in contrib/schemas/.

Usage:
    python -m contrib.check_agent_plugin           # exit 1 on any problem
    python -m contrib.check_agent_plugin --json

Exit codes:
    0: no problems
    1: at least one problem
    2: internal error
"""

import json
import re
import sys
from pathlib import Path

import yaml
from jsonschema import Draft202012Validator

from contrib import gen_agent_manifests

pep440_to_semver = gen_agent_manifests.pep440_to_semver

REPO_ROOT = Path(__file__).resolve().parent.parent
AGENT_PLUGINS_SCHEMA = (
    REPO_ROOT / "contrib" / "schemas" / "agent-plugins-1.0.0.plugin.schema.json"
)

# https://agentskills.io/specification
SKILL_NAME = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MAX_SKILL_NAME = 64
MAX_DESCRIPTION = 1024

# Markdown links whose target is a relative path, e.g. (../../reference/safety.md)
RELATIVE_LINK = re.compile(r"\]\((\.{1,2}/[^)#\s]+)(?:#[^)]*)?\)")


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


class _StrictLoader(yaml.SafeLoader):
    """A SafeLoader that rejects a mapping key defined twice."""


def _no_duplicate_keys(loader, node, deep=False):
    mapping = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in mapping:
            raise yaml.MarkedYAMLError(
                f"duplicate mapping key {key!r}", key_node.start_mark
            )
        mapping[key] = loader.construct_object(value_node, deep=deep)
    return mapping


_StrictLoader.add_constructor(
    yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _no_duplicate_keys
)


def frontmatter(path: Path) -> dict:
    """The frontmatter mapping of a Markdown file, with a parse problem.

    Claude Code reads frontmatter leniently, but other Agent Skills clients
    use strict YAML parsers, so a duplicate key is reported rather than
    silently resolved to the last value.
    """
    text = path.read_text(encoding="utf-8")
    match = re.match(r"^---\r?\n([\s\S]*?)\r?\n---\r?\n", text)
    if not match:
        return {"data": None, "text": text}
    try:
        return {"data": yaml.load(match.group(1), Loader=_StrictLoader) or {}, "text": text}
    except yaml.YAMLError as err:
        return {"data": None, "text": text, "error": str(err).split("\n")[0]}


def release_versions(manifest_path: Path) -> dict:
    """Every file that carries the release version, converted to one form.

    The manifests hold the semver conversion of the pyproject version, so
    both sides go through :func:`pep440_to_semver` before comparing.
    """
    pyproject = (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version\s*=\s*"([^"]+)"', pyproject, re.MULTILINE)
    return {
        "pyproject.toml": pep440_to_semver(match.group(1)) if match else None,
        str(manifest_path.relative_to(REPO_ROOT)): read_json(manifest_path).get("version"),
    }


def check_links(path: Path, text: str, problems: list) -> None:
    for match in RELATIVE_LINK.finditer(text):
        target = match.group(1)
        if not (path.parent / target).resolve().exists():
            problems.append(
                {
                    "file": str(path.relative_to(REPO_ROOT)),
                    "problem": f"link target not found: {target}",
                }
            )


def check_skills(plugin_root: Path, problems: list) -> None:
    skills_dir = plugin_root / "skills"
    if not skills_dir.is_dir():
        problems.append(
            {
                "file": str(skills_dir.relative_to(REPO_ROOT)),
                "problem": "skills directory not found",
            }
        )
        return
    for entry in sorted(skills_dir.iterdir()):
        if not entry.is_dir():
            continue
        skill_file = entry / "SKILL.md"
        rel = str(skill_file.relative_to(REPO_ROOT))
        if not skill_file.exists():
            problems.append({"file": rel, "problem": "missing SKILL.md"})
            continue
        parsed = frontmatter(skill_file)
        data = parsed.get("data")
        if data is None:
            problems.append(
                {
                    "file": rel,
                    "problem": (
                        f"invalid YAML frontmatter: {parsed['error']}"
                        if parsed.get("error")
                        else "missing YAML frontmatter"
                    ),
                }
            )
            continue
        if data.get("name") != entry.name:
            problems.append(
                {
                    "file": rel,
                    "problem": f'name "{data.get("name")}" does not match its directory "{entry.name}"',
                }
            )
        if not SKILL_NAME.match(entry.name) or len(entry.name) > MAX_SKILL_NAME:
            problems.append(
                {
                    "file": rel,
                    "problem": "name must be lowercase letters, digits and single hyphens, at most 64 characters",
                }
            )
        description = data.get("description")
        if not isinstance(description, str) or not description.strip():
            problems.append({"file": rel, "problem": "missing description"})
        elif len(description) > MAX_DESCRIPTION:
            problems.append(
                {
                    "file": rel,
                    "problem": f"description is {len(description)} characters, over the {MAX_DESCRIPTION} limit",
                }
            )
        check_links(skill_file, parsed["text"], problems)


def check_agents(plugin_root: Path, problems: list) -> None:
    agents_dir = plugin_root / "agents"
    if not agents_dir.is_dir():
        return
    for entry in sorted(agents_dir.iterdir()):
        if not entry.name.endswith(".md"):
            continue
        rel = str(entry.relative_to(REPO_ROOT))
        parsed = frontmatter(entry)
        if parsed.get("error"):
            problems.append(
                {"file": rel, "problem": f"invalid YAML frontmatter: {parsed['error']}"}
            )
            continue
        data = parsed.get("data") or {}
        if not data.get("name") or not data.get("description"):
            problems.append({"file": rel, "problem": "agent needs a name and a description"})
        check_links(entry, parsed.get("text", ""), problems)


def check_hooks(plugin_root: Path, problems: list) -> None:
    """Hook scripts named through ${CLAUDE_PLUGIN_ROOT} must exist."""
    hooks_file = plugin_root / "hooks" / "hooks.json"
    if not hooks_file.exists():
        return
    rel = str(hooks_file.relative_to(REPO_ROOT))
    hooks = read_json(hooks_file).get("hooks", {})
    for groups in (hooks or {}).values():
        for group in groups or []:
            for handler in group.get("hooks", []) or []:
                for arg in [handler.get("command"), *(handler.get("args") or [])]:
                    match = re.search(r"\$\{CLAUDE_PLUGIN_ROOT\}/([^\s\"']+)", arg or "")
                    if match and not (plugin_root / match.group(1)).exists():
                        problems.append(
                            {
                                "file": rel,
                                "problem": f"hook script not found: {match.group(1)}",
                            }
                        )


def check_mcp_configs(plugin_root: Path, problems: list) -> None:
    """The Claude Code and Codex MCP configurations must be identical."""
    claude = plugin_root / ".mcp.json"
    codex = plugin_root / "mcp.json"
    if not claude.exists() and not codex.exists():
        return
    if not claude.exists() or not codex.exists():
        problems.append(
            {
                "file": str(plugin_root.relative_to(REPO_ROOT)),
                "problem": "the plugin ships one of .mcp.json and mcp.json but not both",
            }
        )
        return
    if claude.read_bytes() != codex.read_bytes():
        problems.append(
            {
                "file": str(claude.relative_to(REPO_ROOT)),
                "problem": "differs from mcp.json; the two MCP configurations must be identical",
            }
        )
    servers = (read_json(claude).get("mcpServers") or {}).values()
    for server in servers:
        if server.get("args") != ["mcp"]:
            problems.append(
                {
                    "file": str(claude.relative_to(REPO_ROOT)),
                    "problem": "the MCP server must start as `depscan mcp` with no further arguments",
                }
            )
    text = claude.read_text(encoding="utf-8")
    if "allow-scans" in text:
        problems.append(
            {
                "file": str(claude.relative_to(REPO_ROOT)),
                "problem": "the shipped MCP configuration passes --allow-scans, which only the person who starts the server may grant",
            }
        )


def check_agent_plugins_manifest(plugin_root: Path, problems: list) -> None:
    """agent-plugin/plugin.json is validated against the vendored schema."""
    path = plugin_root / "plugin.json"
    rel = str(path.relative_to(REPO_ROOT))
    if not path.exists():
        problems.append({"file": rel, "problem": "Agent Plugins manifest not found"})
        return
    schema = read_json(AGENT_PLUGINS_SCHEMA)
    validator = Draft202012Validator(schema)
    for error in sorted(validator.iter_errors(read_json(path)), key=lambda e: list(e.path)):
        location = "/".join(str(part) for part in error.path) or "/"
        problems.append({"file": rel, "problem": f"schema: {location} {error.message}"})


def check_codex_marketplace(problems: list) -> None:
    """Codex lists the plugin in .agents/plugins/marketplace.json.

    Every entry needs a policy and a category, and source.path must lead to
    a plugin directory.
    https://developers.openai.com/codex/plugins/build#marketplace-metadata
    """
    path = REPO_ROOT / ".agents" / "plugins" / "marketplace.json"
    rel = str(path.relative_to(REPO_ROOT))
    if not path.exists():
        problems.append({"file": rel, "problem": "Codex marketplace not found"})
        return
    for plugin in read_json(path).get("plugins", []):
        plugin_path = (plugin.get("source") or {}).get("path")
        if not plugin_path or not plugin_path.startswith("./"):
            problems.append(
                {
                    "file": rel,
                    "problem": f"{plugin.get('name')}: source.path must start with ./",
                }
            )
        elif not (REPO_ROOT / plugin_path / "plugin.json").exists():
            problems.append(
                {
                    "file": rel,
                    "problem": f"{plugin.get('name')}: no plugin.json under {plugin_path}",
                }
            )
        for field, value in (
            ("policy.installation", (plugin.get("policy") or {}).get("installation")),
            ("policy.authentication", (plugin.get("policy") or {}).get("authentication")),
            ("category", plugin.get("category")),
        ):
            if not value:
                problems.append({"file": rel, "problem": f"{plugin.get('name')}: missing {field}"})


def collect_problems(repo_root: Path | None = None) -> list:
    """Every problem in the plugin, or in ``repo_root`` when a test passes one.

    The generator module keeps its own repository root, so both roots move
    together and a temporary tree is checked the same way as the checkout.
    """
    global REPO_ROOT
    original_root = REPO_ROOT
    original_gen_root = gen_agent_manifests.REPO_ROOT
    if repo_root is not None:
        REPO_ROOT = repo_root
        gen_agent_manifests.REPO_ROOT = repo_root
    try:
        problems = []
        for file in gen_agent_manifests.stale_manifests():
            problems.append(
                {
                    "file": file,
                    "problem": "differs from the generated output; run `python -m contrib.gen_agent_manifests`",
                }
            )
        marketplace = read_json(REPO_ROOT / ".claude-plugin" / "marketplace.json")
        for plugin in marketplace.get("plugins", []):
            source = plugin.get("source")
            if not isinstance(source, str) or not source.startswith("./"):
                problems.append(
                    {
                        "file": ".claude-plugin/marketplace.json",
                        "problem": f"{plugin.get('name')}: source must be a ./ path in this repository",
                    }
                )
                continue
            plugin_root = (REPO_ROOT / source).resolve()
            manifest = plugin_root / ".claude-plugin" / "plugin.json"
            if not manifest.exists():
                problems.append(
                    {"file": plugin.get("source", ""), "problem": "plugin manifest not found"}
                )
                continue
            if read_json(manifest).get("name") != plugin.get("name"):
                problems.append(
                    {
                        "file": str(manifest.relative_to(REPO_ROOT)),
                        "problem": f'name does not match the marketplace entry "{plugin.get("name")}"',
                    }
                )
            versions = release_versions(manifest)
            if len(set(versions.values())) != 1:
                problems.append(
                    {
                        "file": str(manifest.relative_to(REPO_ROOT)),
                        "problem": "release versions differ: "
                        + ", ".join(f"{name}={value}" for name, value in versions.items()),
                    }
                )
            check_agent_plugins_manifest(plugin_root, problems)
            check_skills(plugin_root, problems)
            check_agents(plugin_root, problems)
            check_hooks(plugin_root, problems)
            check_mcp_configs(plugin_root, problems)
        check_codex_marketplace(problems)
        return problems
    finally:
        REPO_ROOT = original_root
        gen_agent_manifests.REPO_ROOT = original_gen_root


def main() -> int:
    try:
        problems = collect_problems()
    except Exception as err:  # noqa: BLE001 - the CLI reports and exits 2
        print(err, file=sys.stderr)
        return 2
    if "--json" in sys.argv[1:]:
        print(json.dumps({"problems": problems, "total": len(problems)}, indent=2))
    elif problems:
        print(f"{len(problems)} problem(s) in the agent plugin:", file=sys.stderr)
        for item in problems:
            print(f"  {item['file']}: {item['problem']}", file=sys.stderr)
    else:
        print("Agent plugin checks passed.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
